"""Generate one install profile per role router: catalog/profiles/<role>.txt
lists the role's skills from this repository (its `requires` closure) and the
external skills to install from upstream.

Usage: build-profiles.py [--check] [--root DIR]
  --check  Compare the committed profiles with freshly generated ones; exit 1 on drift.
Exit status: 0 on success, 1 on drift, 2 on usage errors.
"""

import sys
from pathlib import Path

import skillcatalog

HEADER = "# Generated by scripts/build-profiles.py from metadata.requires. Do not edit.\n"


def render(repo: skillcatalog.Repo, role: str) -> str:
    skills, external = skillcatalog.closure(repo, role)
    lines = [HEADER, *(f"{name}\n" for name in skills)]
    lines += [f"# external {repo.external[name]}: {name}\n" for name in external]
    return "".join(lines)


def main(arguments: list[str]) -> int:
    check = "--check" in arguments
    rest = [argument for argument in arguments if argument != "--check"]
    root = Path(".")
    if rest[:1] == ["--root"] and len(rest) == 2:
        root = Path(rest[1])
    elif rest:
        print(__doc__.strip(), file=sys.stderr)
        return 2

    repo = skillcatalog.load(root)
    profiles = root / "catalog" / "profiles"
    try:
        wanted = {
            f"{name}.txt": render(repo, name)
            for name, entry in repo.entries.items()
            if (entry or {}).get("kind") == "role" and name in repo.frontmatter
        }
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1
    existing = {path.name: path.read_text(encoding="utf-8") for path in profiles.glob("*.txt")} if profiles.is_dir() else {}

    if check:
        drift = sorted(name for name in set(wanted) | set(existing) if wanted.get(name) != existing.get(name))
        for name in drift:
            print(f"  - catalog/profiles/{name} is out of date")
        if drift:
            print("Profiles drifted; run scripts/build-profiles.py and commit the result.")
            return 1
        print("Profiles are up to date.")
        return 0

    profiles.mkdir(parents=True, exist_ok=True)
    for name in set(existing) - set(wanted):
        (profiles / name).unlink()
    for name, text in wanted.items():
        (profiles / name).write_text(text, encoding="utf-8")
    print(f"Wrote {len(wanted)} profile(s) to {profiles}.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
