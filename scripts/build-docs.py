# A strict YAML subset: block mappings and sequences, empty mappings, flow
# sequences of plain scalars, single-line scalars, and comments. Everything else fails.
def _scalar(text: str, where: str):
    text = text.strip()
    rest = ""
    if text.startswith('"'):
        chars, index = [], 1
        escapes = {'"': '"', "\\": "\\", "n": "\n", "t": "\t", "/": "/"}
        while index < len(text) and text[index] != '"':
            if text[index] == "\\":
                if index + 1 >= len(text) or text[index + 1] not in escapes:
                    raise SourceError(f"{where}: unsupported escape in a double-quoted value; use a plain character")
                chars.append(escapes[text[index + 1]])
                index += 2
            else:
                chars.append(text[index])
                index += 1
        if index >= len(text):
            raise SourceError(f"{where}: unterminated double-quoted value; keep each value on one line")
        value, rest = "".join(chars), text[index + 1:].strip()
    elif text.startswith("'"):
        chars, index = [], 1
        while True:
            if index >= len(text):
                raise SourceError(f"{where}: unterminated single-quoted value; keep each value on one line")
            if text[index] == "'":
                if text[index + 1:index + 2] == "'":
                    chars.append("'")
                    index += 2
                    continue
                break
            chars.append(text[index])
            index += 1
        value, rest = "".join(chars), text[index + 1:].strip()
    elif text.startswith("["):
        body = re.split(r"\s#", text, maxsplit=1)[0].rstrip()
        if not body.endswith("]"):
            raise SourceError(f"{where}: a flow list must open and close on one line")
        items = [item.strip() for item in body[1:-1].split(",")] if body[1:-1].strip() else []
        for item in items:
            if not item or re.search(r"[\[\]{}\"'#&*!|>]|:\s|:$", item):
                raise SourceError(f"{where}: flow lists may hold only plain names; got {item!r}")
        return [_scalar(item, where) for item in items]
    elif re.fullmatch(r"\{\}(?:\s+#.*)?", text):
        return {}
    elif text[:1] in set("{&*!|>%@`"):
        raise SourceError(f"{where}: unsupported YAML syntax {text[:1]!r}; use a plain or quoted single-line value")
    else:
        value = re.split(r"\s#", text, maxsplit=1)[0].rstrip()
        if re.match(r"^[,\]{}]|^[-?:](?:\s|$)", value):
            raise SourceError(f"{where}: unsupported YAML plain scalar; quote the value")
        # This subset supports strings, not YAML's implicit typed scalars.
        typed = (
            re.fullmatch(r"(?:~|null|true|false|yes|no|on|off)", value, re.I)
            or re.fullmatch(r"[-+]?(?:[0-9][0-9_:]*(?:\.[0-9_]*)?(?:[eE][-+]?[0-9]+)?|"
                            r"\.[0-9_]+(?:[eE][-+]?[0-9]+)?|0[bBoOxX][0-9a-fA-F_]+|"
                            r"\.(?:inf|nan))", value, re.I)
            or re.match(r"\d{4}-\d{1,2}-\d{1,2}(?:$|[Tt\s])", value)
        )
        if typed:
            raise SourceError(f"{where}: unsupported implicit YAML type; quote the string value")
        if re.search(r":\s|:$", value):
            raise SourceError(f"{where}: a plain value cannot contain ': '; quote it")
        return value
    if rest and not rest.startswith("#"):
        raise SourceError(f"{where}: unexpected text after a quoted value")
    return value


def load_yaml(text: str, where: str):
    rows = []
    for number, raw in enumerate(text.splitlines(), 1):
        body = raw.rstrip()
        stripped = body.lstrip(" ")
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.startswith("\t"):
            raise SourceError(f"{where}:{number}: tab indentation; indent with spaces")
        if stripped in ("---", "..."):
            raise SourceError(f"{where}:{number}: multiple YAML documents are unsupported")
        rows.append((number, len(body) - len(stripped), stripped))
    if not rows:
        return {}
    value, index = _block(rows, 0, rows[0][1], where)
    if index != len(rows):
        raise SourceError(f"{where}:{rows[index][0]}: unexpected indentation")
    return value


def _is_item(text: str) -> bool:
    return text == "-" or text.startswith("- ")


def _block(rows, index, indent, where):
    number, level, text = rows[index]
    if level != indent:
        raise SourceError(f"{where}:{number}: unexpected indentation")
    return (_sequence if _is_item(text) else _mapping)(rows, index, indent, where)


def _sequence(rows, index, indent, where):
    items = []
    while index < len(rows) and rows[index][1] == indent and _is_item(rows[index][2]):
        number, _, text = rows[index]
        item = text[1:].strip()
        if not item or re.match(r"[^\"'\[][^#]*?:(\s|$)", item):
            raise SourceError(f"{where}:{number}: list items must be single values")
        items.append(_scalar(item, f"{where}:{number}"))
        index += 1
    if index < len(rows) and rows[index][1] > indent:
        raise SourceError(f"{where}:{rows[index][0]}: unexpected indentation")
    return items, index


def _mapping(rows, index, indent, where):
    result = {}
    while index < len(rows) and rows[index][1] == indent:
        number, _, text = rows[index]
        match = re.fullmatch(r"([A-Za-z0-9_][A-Za-z0-9_.-]*):(?:\s+(.*))?", text)
        if not match or _is_item(text):
            raise SourceError(f"{where}:{number}: expected 'key: value'")
        key, rest = match[1], (match[2] or "").strip()
        if key in result:
            raise SourceError(f"{where}:{number}: duplicate key {key}")
        index += 1
        if rest and not rest.startswith("#"):
            result[key] = _scalar(rest, f"{where}:{number}")
        elif index < len(rows) and rows[index][1] > indent:
            result[key], index = _block(rows, index, rows[index][1], where)
        elif index < len(rows) and rows[index][1] == indent and _is_item(rows[index][2]):
            result[key], index = _sequence(rows, index, indent, where)
        else:
            result[key] = None
    if index < len(rows) and rows[index][1] > indent:
        raise SourceError(f"{where}:{rows[index][0]}: unexpected indentation")
    return result, index


def frontmatter(path: Path, root: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    match = re.match(r"---\n(.*?)\n---\n", text, re.DOTALL)
    where = path.relative_to(root).as_posix()
    if not match:
        raise SourceError(f"{where}: missing '---' frontmatter")
    data = load_yaml("\n" + match[1], where)  # Line numbers then match the file.
    if not isinstance(data, dict):
        raise SourceError(f"{where}: frontmatter must be a mapping")
    return data, text[match.end():]


@dataclass
class Skill:
    name: str
    kind: str
    roles: list
    invocation: str
    status: str
    aliases: list
    description: str
    requires: list
    routes: list
    source: str | None
    revision: str | None
    legal: list
    examples: dict
    body: str
    required_by: list = field(default_factory=list)
    closure: list = field(default_factory=list)

    @property
    def summary(self) -> str:
        match = re.match(r"(.+?[.!?])(?=\s|$)", self.description)
        return match[1] if match else self.description

    @property
    def typed(self) -> bool:
        return self.invocation == "user"


@dataclass
class Repo:
    root: Path
    skills: dict
    external: dict
    reserved: set
    records: list
    guidance: list
    evaluations: list
    result_paths: list


def result_markdown(root: Path) -> list[Path]:
    """Only committed/staged records in a checkout; all shipped records in an export."""
    if (root / ".git").exists():
        try:
            result = subprocess.run(["git", "-C", str(root), "ls-files", "-z", "--", "skills/*/evals/results/*.md"],
                                    capture_output=True, check=True)
        except (OSError, subprocess.CalledProcessError) as error:
            raise SourceError("skills/*/evals/results/: cannot enumerate tracked records; install Git or validate a clean repository export") from error
        return sorted(root / name for name in result.stdout.decode().split("\0") if name and (root / name).is_file())
    return sorted((root / "skills").glob("*/evals/results/**/*.md"))


def package_digest(directory: Path) -> str:
    """Match evalharness.isolation.manifest(skill=True) and tree_digest exactly."""
    files = {}
    for path in sorted(directory.rglob("*")):
        relative = path.relative_to(directory)
        if relative.parts[:2] == ("evals", "results"):
            continue
        if path.is_symlink():
            raise SourceError(f"skills/{directory.name}/{relative}: skill inputs must be regular files")
        if path.is_file():
            files[relative.as_posix()] = {"sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                                        "executable": bool(path.stat().st_mode & 0o111)}
    return hashlib.sha256(json.dumps(files, sort_keys=True).encode()).hexdigest()


def parse_evaluation(path: Path, current_digest: str) -> dict:
    # Prompts are fenced data. A prompt quoting a table or Value line must not
    # become an observation or a review judgment in the generated results.
    text = skillprose.prose(path.read_text(encoding="utf-8"))
    status = RECORD.search(text)
    host = re.search(r"^# [^\n]+: (claude|codex)\b", text, re.M)
    source = re.search(r"^- \*\*Source example\.\*\* `([^`]+)`", text, re.M)
    digest = re.search(r"actual bytes SHA-256 `([a-f0-9]{64})`", text)
    arms = {}
    for line in text.splitlines():
        fields = [value.strip() for value in line.split("|")[1:-1]]
        if len(fields) == 5 and fields[0] in ("treatment", "baseline"):
            arms[fields[0]] = fields[1:]
    complete = set(arms) == {"treatment", "baseline"} and all(
        fields[1] in ("true", "false") and fields[2].isdigit() and fields[3] == "0"
        for fields in arms.values())
    validity = status[1] if status else "unparsed"
    if validity != "valid":
        history = "invalid" if validity == "invalid" else "incomplete or other"
    elif not digest or digest[1] != current_digest:
        history = "older or unbound"
    else:
        history = "" if complete else "incomplete or other"
    observed = arms.get("treatment", ["unknown", "unknown"])[1]
    # Retain the table's values, except where the record explicitly reviews an
    # observer miss. Last reviewed correction wins; no free-text inference.
    reviewed = re.findall(r"Reviewed activation:\s*treatment\s+\*{0,2}(true|false)\*{0,2},\s*baseline\s+\*{0,2}(true|false)", text, re.I)
    if reviewed:
        observed = reviewed[-1][0].lower()
    values = re.findall(r"\bValue:\s*\*{0,2}(added|matched|hurt|blocked)\b", text, re.I)
    return {"path": path, "skill": path.parts[-4], "host": host[1] if host else "unknown",
            "status": validity, "example": source[1] if source else "unknown",
            "expected": arms.get("treatment", ["unknown"])[0], "observed": observed,
            "value": values[-1].lower() if values else "unreviewed", "history": history}


def load(root: Path) -> Repo:
    catalog_path = root / "catalog" / "skills.yaml"
    try:
        catalog = load_yaml(catalog_path.read_text(encoding="utf-8"), "catalog/skills.yaml")
    except OSError as error:
        raise SourceError(f"catalog/skills.yaml: unreadable ({error})") from error
    if not isinstance(catalog, dict) or not isinstance(catalog.get("skills") or {}, dict):
        raise SourceError("catalog/skills.yaml: expected a mapping with a skills: mapping")
    entries = catalog.get("skills") or {}
    external = {}
    for provider, spec in (catalog.get("external") or {}).items():
        for name in (spec or {}).get("skills") or []:
            external[name] = provider
    on_disk = {path.parent.name for path in (root / "skills").glob("*/SKILL.md")}
    if missing := sorted(on_disk - set(entries)):
        raise SourceError(f"catalog/skills.yaml: no entry for {', '.join(missing)}; add them, then rerun")
    if missing := sorted(set(entries) - on_disk):
        raise SourceError(f"skills/: no SKILL.md for catalog entries {', '.join(missing)}")
    bodies, skills = {}, {}
    for name, entry in entries.items():
        entry = entry or {}
        if not isinstance(entry, dict):
            raise SourceError(f"catalog/skills.yaml: entry {name} must be a mapping")
        data, bodies[name] = frontmatter(root / "skills" / name / "SKILL.md", root)
        metadata = data.get("metadata") or {}
        description = data.get("description")
        if not isinstance(description, str) or not isinstance(metadata, dict):
            raise SourceError(f"skills/{name}/SKILL.md: needs a string description and a metadata mapping")
        folder = root / "skills" / name
        legal = sorted(path.name for path in folder.iterdir() if path.is_file() and re.match(r"(LICENSE|NOTICE)-", path.name))
        skills[name] = Skill(
            name=name, kind=entry.get("kind", ""), roles=list(entry.get("roles") or []),
            invocation=entry.get("invocation") or "model", status=entry.get("status", ""),
            aliases=list(entry.get("aliases") or []), description=" ".join(description.split()),
            requires=str(metadata.get("requires") or "").split(), routes=[],
            source=metadata.get("source"), revision=metadata.get("source-revision"), legal=legal,
            examples=read_examples(folder / "evals/examples.md"), body=bodies[name])
    known = set(skills) | set(external)
    for name, skill in skills.items():
        if unknown := [target for target in skill.requires if target not in known]:
            raise SourceError(f"skills/{name}/SKILL.md: metadata.requires names {', '.join(unknown)}, which is neither a skill nor external")
        found = []
        resources, errors = skillprose.linked_resources(root / "skills" / name)
        if errors:
            raise SourceError("; ".join(errors))
        texts = [bodies[name]]
        for resource in resources:
            try:
                texts.append(resource.read_text(encoding="utf-8"))
            except UnicodeDecodeError:
                pass
        for line in skillprose.prose("\n".join(texts)).splitlines():
            for match in skillprose.POINTER.finditer(line):
                target = match["name"]
                if target in known and target != name and target not in skill.requires and target not in found:
                    found.append(target)
        skill.routes = sorted(found)
        skill.required_by = sorted(other for other, candidate in skills.items() if name in candidate.requires)
        seen, pending = set(), [name]
        while pending:
            current = pending.pop()
            if current not in seen:
                seen.add(current)
                pending.extend(skills[current].requires if current in skills else [])
        skill.closure = sorted(seen)
    reserved = set()
    reserved_file = root / "catalog" / "reserved-names.txt"
    if reserved_file.is_file():
        for line in reserved_file.read_text(encoding="utf-8").splitlines():
            if line := line.split("#", 1)[0].strip():
                reserved.add(line)
    records, evaluations = [], []
    result_paths = result_markdown(root)
    digests = {name: package_digest(root / "skills" / name) for name in skills}
    for path in result_paths:
        if len(path.relative_to(root).parts) != 5:
            continue  # Raw evidence is not a public paired summary.
        match = RECORD.search(path.read_text(encoding="utf-8"))
        records.append((match[1], match[2] or "not recorded", match[3] or "not recorded") if match else ("unparsed", "not recorded", "not recorded"))
        evaluations.append(parse_evaluation(path, digests.get(path.parts[-4], "")))
    guidance = json.loads((root / "handbook/intent-guide.json").read_text(encoding="utf-8"))
    groups = guidance.get("groups") if isinstance(guidance, dict) else None
    if not isinstance(groups, list):
        raise SourceError("handbook/intent-guide.json: needs a groups list; restore its documented schema")
    covered = set()
    for group in groups:
        if not isinstance(group, dict) or not isinstance(group.get("heading"), str) or not group["heading"].strip() or not isinstance(group.get("entries"), list):
            raise SourceError("handbook/intent-guide.json: each group needs a heading and entries list")
        if not isinstance(group.get("heading_id"), str) or not group["heading_id"].strip():
            raise SourceError("handbook/intent-guide.json: each group needs a nonempty Indonesian heading_id field")
        for row in group["entries"]:
            if not isinstance(row, dict) or not {"skill", "want", "prompt", "neighbor"} <= set(row) or not all(isinstance(v, str) for v in row.values()):
                raise SourceError("handbook/intent-guide.json: each row needs string skill, want, prompt and neighbor fields")
            if not all(isinstance(row.get(key), str) and row[key].strip() for key in ("want_id", "neighbor_id")):
                raise SourceError("handbook/intent-guide.json: each row needs nonempty Indonesian want_id and neighbor_id fields")
            if set(row) != {"skill", "want", "prompt", "neighbor", "want_id", "neighbor_id"}:
                raise SourceError("handbook/intent-guide.json: unknown editorial field; keep the bilingual row schema")
            name = row["skill"]
            if name not in skills:
                raise SourceError(f"handbook/intent-guide.json: unknown skill {name}; use a catalog skill in each README category")
            if name in covered:
                raise SourceError(f"handbook/intent-guide.json: duplicate skill {name}; list each skill in exactly one README category")
            if not row["want"].strip() or not row["neighbor"].strip():
                raise SourceError(f"handbook/intent-guide.json: empty guidance for {name}; repair its intent row")
            covered.add(name)
    if missing := sorted(set(skills) - covered):
        raise SourceError("handbook/intent-guide.json: no intent guidance for " + ", ".join(missing) + "; add one useful row per skill in its README category, then run scripts/build-docs.py")
    for skill in skills.values():
        if skill.kind not in ("role", "capability") or skill.invocation not in ("model", "user") or skill.status not in ("evaluated", "unevaluated"):
            raise SourceError(f"catalog/skills.yaml: invalid kind, invocation or status for {skill.name}; run scripts/check-catalog.py")
    expected = {}
    for skill in skills.values():
        if skill.kind == "role":
            owned = [name for name in skill.closure if name in skills]
            outside = [name for name in skill.closure if name in external]
            expected[skill.name + ".txt"] = "# Generated by scripts/build-profiles.py from metadata.requires. Do not edit.\n" + "".join(name + "\n" for name in owned) + "".join(f"# external {external[name]}: {name}\n" for name in outside)
    actual = {path.name: path.read_text(encoding="utf-8") for path in (root / "catalog/profiles").glob("*.txt")}
    if actual != expected:
        raise SourceError("catalog/profiles: profile drift; run scripts/build-profiles.py and commit the result")
    return Repo(root=root, skills=skills,
                external=external, reserved=reserved, records=records, guidance=groups,
                evaluations=evaluations, result_paths=result_paths)


def read_examples(path: Path) -> dict:
    result = {"Activation": [], "Near miss": [], "Outcome": []}
    section = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            section = line[3:].strip()
        elif line.startswith("- ") and section in result:
            result[section].append(line[2:])
    if any(not rows for rows in result.values()):
        raise SourceError(f"{path.parent.parent.name}: examples need Activation, Near miss and Outcome items")
    return result


