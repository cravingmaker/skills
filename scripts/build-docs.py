# A strict YAML subset: block mappings and sequences, flow sequences of plain
# scalars, plain and quoted single-line scalars, and comments. Everything else fails.
def _scalar(text: str, where: str):
    text = text.strip()
    rest = ""
    if text.startswith('"'):
        chars, index = [], 1
        escapes = {'"': '"', "\\": "\\", "n": "\n", "t": "\t", "/": "/"}
        while index < len(text) and text[index] != '"':
            if text[index] == "\\":
                if index + 1 >= len(text) or text[index + 1] not in escapes:
                    raise SourceError(f"{where}: unsupported escape in a double-quoted value; use a plain character")
                chars.append(escapes[text[index + 1]])
                index += 2
            else:
                chars.append(text[index])
                index += 1
        if index >= len(text):
            raise SourceError(f"{where}: unterminated double-quoted value; keep each value on one line")
        value, rest = "".join(chars), text[index + 1:].strip()
    elif text.startswith("'"):
        chars, index = [], 1
        while True:
            if index >= len(text):
                raise SourceError(f"{where}: unterminated single-quoted value; keep each value on one line")
            if text[index] == "'":
                if text[index + 1:index + 2] == "'":
                    chars.append("'")
                    index += 2
                    continue
                break
            chars.append(text[index])
            index += 1
        value, rest = "".join(chars), text[index + 1:].strip()
    elif text.startswith("["):
        body = re.split(r"\s#", text, maxsplit=1)[0].rstrip()
        if not body.endswith("]"):
            raise SourceError(f"{where}: a flow list must open and close on one line")
        items = [item.strip() for item in body[1:-1].split(",")] if body[1:-1].strip() else []
        for item in items:
            if not item or re.search(r"[\[\]{}\"'#&*!|>]|:\s|:$", item):
                raise SourceError(f"{where}: flow lists may hold only plain names; got {item!r}")
        return [_scalar(item, where) for item in items]
    elif text[:1] in set("{&*!|>%@`"):
        raise SourceError(f"{where}: unsupported YAML syntax {text[:1]!r}; use a plain or quoted single-line value")
    else:
        value = re.split(r"\s#", text, maxsplit=1)[0].rstrip()
        if re.match(r"^[,\]{}]|^[-?:](?:\s|$)", value):
            raise SourceError(f"{where}: unsupported YAML plain scalar; quote the value")
        # This subset supports strings, not YAML's implicit typed scalars.
        typed = (
            re.fullmatch(r"(?:~|null|true|false|yes|no|on|off)", value, re.I)
            or re.fullmatch(r"[-+]?(?:[0-9][0-9_:]*(?:\.[0-9_]*)?(?:[eE][-+]?[0-9]+)?|"
                            r"\.[0-9_]+(?:[eE][-+]?[0-9]+)?|0[bBoOxX][0-9a-fA-F_]+|"
                            r"\.(?:inf|nan))", value, re.I)
            or re.match(r"\d{4}-\d{1,2}-\d{1,2}(?:$|[Tt\s])", value)
        )
        if typed:
            raise SourceError(f"{where}: unsupported implicit YAML type; quote the string value")
        if re.search(r":\s|:$", value):
            raise SourceError(f"{where}: a plain value cannot contain ': '; quote it")
        return value
    if rest and not rest.startswith("#"):
        raise SourceError(f"{where}: unexpected text after a quoted value")
    return value


def load_yaml(text: str, where: str):
    rows = []
    for number, raw in enumerate(text.splitlines(), 1):
        body = raw.rstrip()
        stripped = body.lstrip(" ")
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.startswith("\t"):
            raise SourceError(f"{where}:{number}: tab indentation; indent with spaces")
        if stripped in ("---", "..."):
            raise SourceError(f"{where}:{number}: multiple YAML documents are unsupported")
        rows.append((number, len(body) - len(stripped), stripped))
    if not rows:
        return {}
    value, index = _block(rows, 0, rows[0][1], where)
    if index != len(rows):
        raise SourceError(f"{where}:{rows[index][0]}: unexpected indentation")
    return value


def _is_item(text: str) -> bool:
    return text == "-" or text.startswith("- ")


def _block(rows, index, indent, where):
    number, level, text = rows[index]
    if level != indent:
        raise SourceError(f"{where}:{number}: unexpected indentation")
    return (_sequence if _is_item(text) else _mapping)(rows, index, indent, where)


def _sequence(rows, index, indent, where):
    items = []
    while index < len(rows) and rows[index][1] == indent and _is_item(rows[index][2]):
        number, _, text = rows[index]
        item = text[1:].strip()
        if not item or re.match(r"[^\"'\[][^#]*?:(\s|$)", item):
            raise SourceError(f"{where}:{number}: list items must be single values")
        items.append(_scalar(item, f"{where}:{number}"))
        index += 1
    if index < len(rows) and rows[index][1] > indent:
        raise SourceError(f"{where}:{rows[index][0]}: unexpected indentation")
    return items, index


def _mapping(rows, index, indent, where):
    result = {}
    while index < len(rows) and rows[index][1] == indent:
        number, _, text = rows[index]
        match = re.fullmatch(r"([A-Za-z0-9_][A-Za-z0-9_.-]*):(?:\s+(.*))?", text)
        if not match or _is_item(text):
            raise SourceError(f"{where}:{number}: expected 'key: value'")
        key, rest = match[1], (match[2] or "").strip()
        if key in result:
            raise SourceError(f"{where}:{number}: duplicate key {key}")
        index += 1
        if rest and not rest.startswith("#"):
            result[key] = _scalar(rest, f"{where}:{number}")
        elif index < len(rows) and rows[index][1] > indent:
            result[key], index = _block(rows, index, rows[index][1], where)
        elif index < len(rows) and rows[index][1] == indent and _is_item(rows[index][2]):
            result[key], index = _sequence(rows, index, indent, where)
        else:
            result[key] = None
    if index < len(rows) and rows[index][1] > indent:
        raise SourceError(f"{where}:{rows[index][0]}: unexpected indentation")
    return result, index


def frontmatter(path: Path, root: Path) -> tuple[dict, str]:
    text = path.read_text(encoding="utf-8")
    match = re.match(r"---\n(.*?)\n---\n", text, re.DOTALL)
    where = path.relative_to(root).as_posix()
    if not match:
        raise SourceError(f"{where}: missing '---' frontmatter")
    data = load_yaml("\n" + match[1], where)  # Line numbers then match the file.
    if not isinstance(data, dict):
        raise SourceError(f"{where}: frontmatter must be a mapping")
    return data, text[match.end():]


@dataclass
class Skill:
    name: str
    kind: str
    roles: list
    invocation: str
    status: str
    aliases: list
    description: str
    requires: list
    routes: list
    source: str | None
    revision: str | None
    legal: list
    examples: dict
    body: str
    required_by: list = field(default_factory=list)
    closure: list = field(default_factory=list)

    @property
    def summary(self) -> str:
        match = re.match(r"(.+?[.!?])(?=\s|$)", self.description)
        return match[1] if match else self.description

    @property
    def typed(self) -> bool:
        return self.invocation == "user"


@dataclass
class Repo:
    root: Path
    roles: list
    skills: dict
    external: dict
    reserved: set
    records: list
    guidance: list


def load(root: Path) -> Repo:
    catalog_path = root / "catalog" / "skills.yaml"
    try:
        catalog = load_yaml(catalog_path.read_text(encoding="utf-8"), "catalog/skills.yaml")
    except OSError as error:
        raise SourceError(f"catalog/skills.yaml: unreadable ({error})") from error
    if not isinstance(catalog, dict) or not isinstance(catalog.get("skills") or {}, dict):
        raise SourceError("catalog/skills.yaml: expected a mapping with a skills: mapping")
    entries = catalog.get("skills") or {}
    external = {}
    for provider, spec in (catalog.get("external") or {}).items():
        for name in (spec or {}).get("skills") or []:
            external[name] = provider
    on_disk = {path.parent.name for path in (root / "skills").glob("*/SKILL.md")}
    if missing := sorted(on_disk - set(entries)):
        raise SourceError(f"catalog/skills.yaml: no entry for {', '.join(missing)}; add them, then rerun")
    if missing := sorted(set(entries) - on_disk):
        raise SourceError(f"skills/: no SKILL.md for catalog entries {', '.join(missing)}")
    bodies, skills = {}, {}
    for name, entry in entries.items():
        entry = entry or {}
        if not isinstance(entry, dict):
            raise SourceError(f"catalog/skills.yaml: entry {name} must be a mapping")
        data, bodies[name] = frontmatter(root / "skills" / name / "SKILL.md", root)
        metadata = data.get("metadata") or {}
        description = data.get("description")
        if not isinstance(description, str) or not isinstance(metadata, dict):
            raise SourceError(f"skills/{name}/SKILL.md: needs a string description and a metadata mapping")
        folder = root / "skills" / name
        legal = sorted(path.name for path in folder.iterdir() if path.is_file() and re.match(r"(LICENSE|NOTICE)-", path.name))
        skills[name] = Skill(
            name=name, kind=entry.get("kind", ""), roles=list(entry.get("roles") or []),
            invocation=entry.get("invocation") or "model", status=entry.get("status", ""),
            aliases=list(entry.get("aliases") or []), description=" ".join(description.split()),
            requires=str(metadata.get("requires") or "").split(), routes=[],
            source=metadata.get("source"), revision=metadata.get("source-revision"), legal=legal,
            examples=read_examples(folder / "evals/examples.md"), body=bodies[name])
    known = set(skills) | set(external)
    for name, skill in skills.items():
        if unknown := [target for target in skill.requires if target not in known]:
            raise SourceError(f"skills/{name}/SKILL.md: metadata.requires names {', '.join(unknown)}, which is neither a skill nor external")
        found = []
        resources, errors = skillprose.linked_resources(root / "skills" / name)
        if errors:
            raise SourceError("; ".join(errors))
        texts = [bodies[name]]
        for resource in resources:
            try:
                texts.append(resource.read_text(encoding="utf-8"))
            except UnicodeDecodeError:
                pass
        for line in skillprose.prose("\n".join(texts)).splitlines():
            for match in skillprose.POINTER.finditer(line):
                target = match["name"]
                if target in known and target != name and target not in skill.requires and target not in found:
                    found.append(target)
        skill.routes = sorted(found)
        skill.required_by = sorted(other for other, candidate in skills.items() if name in candidate.requires)
        seen, pending = set(), [name]
        while pending:
            current = pending.pop()
            if current not in seen:
                seen.add(current)
                pending.extend(skills[current].requires if current in skills else [])
        skill.closure = sorted(seen)
    reserved = set()
    reserved_file = root / "catalog" / "reserved-names.txt"
    if reserved_file.is_file():
        for line in reserved_file.read_text(encoding="utf-8").splitlines():
            if line := line.split("#", 1)[0].strip():
                reserved.add(line)
    records = []
    for path in sorted((root / "skills").glob("*/evals/results/*.md")):
        match = RECORD.search(path.read_text(encoding="utf-8"))
        records.append((match[1], match[2] or "not recorded", match[3] or "not recorded") if match else ("unparsed", "not recorded", "not recorded"))
    guidance = json.loads((root / "handbook/intent-guide.json").read_text(encoding="utf-8"))
    groups = guidance.get("groups") if isinstance(guidance, dict) else None
    if not isinstance(groups, list):
        raise SourceError("handbook/intent-guide.json: needs a groups list; restore its documented schema")
    covered = set()
    for group in groups:
        if not isinstance(group, dict) or not isinstance(group.get("heading"), str) or not isinstance(group.get("entries"), list):
            raise SourceError("handbook/intent-guide.json: each group needs a heading and entries list")
        for row in group["entries"]:
            if not isinstance(row, dict) or set(row) != {"skill", "want", "prompt", "neighbor"} or not all(isinstance(v, str) for v in row.values()):
                raise SourceError("handbook/intent-guide.json: each row needs string skill, want, prompt and neighbor fields")
            name = row["skill"]
            if name not in skills or name in covered or not row["want"].strip() or not row["neighbor"].strip():
                raise SourceError(f"handbook/intent-guide.json: unknown, duplicate or empty guidance for {name}; repair its intent row")
            covered.add(name)
    if missing := sorted(set(skills) - covered):
        raise SourceError("handbook/intent-guide.json: no intent guidance for " + ", ".join(missing) + "; add one useful row per new skill, then run scripts/build-docs.py")
    for skill in skills.values():
        if skill.kind not in ("role", "capability") or skill.invocation not in ("model", "user") or skill.status not in ("evaluated", "unevaluated"):
            raise SourceError(f"catalog/skills.yaml: invalid kind, invocation or status for {skill.name}; run scripts/check-catalog.py")
    expected = {}
    for skill in skills.values():
        if skill.kind == "role":
            owned = [name for name in skill.closure if name in skills]
            outside = [name for name in skill.closure if name in external]
            expected[skill.name + ".txt"] = "# Generated by scripts/build-profiles.py from metadata.requires. Do not edit.\n" + "".join(name + "\n" for name in owned) + "".join(f"# external {external[name]}: {name}\n" for name in outside)
    actual = {path.name: path.read_text(encoding="utf-8") for path in (root / "catalog/profiles").glob("*.txt")}
    if actual != expected:
        raise SourceError("catalog/profiles: profile drift; run scripts/build-profiles.py and commit the result")
    return Repo(root=root, roles=list(catalog.get("roles") or []), skills=skills,
                external=external, reserved=reserved, records=records, guidance=groups)


def read_examples(path: Path) -> dict:
    result = {"Activation": [], "Near miss": [], "Outcome": []}
    section = None
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            section = line[3:].strip()
        elif line.startswith("- ") and section in result:
            result[section].append(line[2:])
    if any(not rows for rows in result.values()):
        raise SourceError(f"{path.parent.parent.name}: examples need Activation, Near miss and Outcome items")
    return result


def render_intent(repo: Repo) -> str:
    def current_modes(text):
        return re.sub(r"`/?([a-z0-9]+(?:-[a-z0-9]+)*)`", lambda m: "`" + ("/" if repo.skills.get(m[1]) and repo.skills[m[1]].typed else "") + m[1] + "`", text)
    parts = []
    for group in repo.guidance:
        lines = ["## " + group["heading"], "", "| I want to... | Use | Start it with | Easily confused with |", "| --- | --- | --- | --- |"]
        for row in group["entries"]:
            skill = repo.skills[row["skill"]]
            selected = ("/" if skill.typed else "") + skill.name
            prompt = (f"`/{skill.name}` " if skill.typed else "") + current_modes(row["prompt"])
            lines.append("| " + " | ".join(cell(value) for value in (row["want"], f"[`{selected}`](skills.md#{skill.name})", prompt.strip(), current_modes(row["neighbor"]))) + " |")
        parts.append("\n".join(lines))
    return "\n\n".join(parts)


def render_workflow(repo: Repo) -> str:
    lines = ["| Router | Task stage | Conditional methods named by the flow |", "| --- | --- | --- |"]
    for skill in repo.skills.values():
        if skill.kind != "role":
            continue
        for heading, body in re.findall(r"(?ms)^### ([^\n]+)\n(.*?)(?=^###? |\Z)", skill.body):
            targets = list(dict.fromkeys(m["name"] for m in skillprose.POINTER.finditer(skillprose.prose(body)) if m["name"] in repo.skills))
            lines.append(f"| [`{skill.name}`](../skills/{skill.name}/SKILL.md) | {cell(heading)} | {names(targets)} |")
    return "\n".join(lines)


def render_roadmap(repo: Repo) -> str:
    priority = ("devops", "sysadmin", "security", "data-engineer", "data-analyst", "data-scientist", "frontend", "mobile", "ui-ux", "qa", "technical", "seo", "business", "financial", "marketing", "copywriter")
    roles = [r for r in repo.roles if r not in repo.skills and not r.startswith("backend-")]
    roles.sort(key=lambda r: next((i for i, prefix in enumerate(priority) if r.startswith(prefix)), len(priority)))
    return "\n".join(["| Planned order after the backend PR | Catalog role |", "| --- | --- |", *(f"| {i} | `{role}` |" for i, role in enumerate(roles, 1))])


def cell(text: str) -> str:
    return text.replace("|", "\\|")


def names(items, anchor: bool = False) -> str:
    if not items:
        return "none"
    return ", ".join(f"[`{item}`](#{item})" if anchor else f"`{item}`" for item in items)


def start(skill: Skill) -> str:
    return "typed" if skill.typed else "auto"


def render_counts(repo: Repo) -> str:
    skills = list(repo.skills.values())
    routers = sum(skill.kind == "role" for skill in skills)
    typed = sum(skill.typed for skill in skills)
    evaluated = sum(skill.status == "evaluated" for skill in skills)
    return (f"**{len(skills)} skills:** {routers} role {'router' if routers == 1 else 'routers'} and "
            f"{len(skills) - routers} capability skills. {typed} prefer explicit selection; "
            f"the agent can pick the other {len(skills) - typed} on its own. "
            f"Evaluation status: {evaluated} evaluated, {len(skills) - evaluated} unevaluated.")


def render_index(repo: Repo) -> str:
    lines = ["**Starts:** *auto* permits selection when the task fits; *typed* requests native explicit selection: "
             "`/<name>` in Claude Code or `$<name>` in Codex. Visibility policy is not filesystem access control.", "",
             "| Skill | Starts | What it does |", "| --- | --- | --- |"]
    for skill in repo.skills.values():
        label = f"{skill.name} (role)" if skill.kind == "role" else skill.name
        lines.append(f"| [{label}](skills/{skill.name}) | {start(skill)} | {cell(skill.summary)} |")
    return "\n".join(lines)


def render_reference(repo: Repo) -> str:
    ordered = sorted(repo.skills.values(), key=lambda skill: skill.name)
    lines = []
    for label, group in (("Typed only", [s for s in ordered if s.typed]), ("Auto", [s for s in ordered if not s.typed])):
        lines.append(f"- **{label} ({len(group)}):** " + ", ".join(f"[`{s.name}`](#{s.name})" for s in group))
    for skill in ordered:
        lines += ["", f"### `{skill.name}`", "", skill.description, ""]
        how = (f"typed only: `/{skill.name}` in Claude Code, `${skill.name}` in Codex" if skill.typed
               else "model selection when the task fits")
        kind = "role router" if skill.kind == "role" else "capability"
        roles = ("every role" if "all" in skill.roles else ", ".join(skill.roles)) if skill.roles else f"router for the `{skill.name}` role"
        lines.append(f"- **Starts:** {how}. **Kind:** {kind}. **Status:** {skill.status}.")
        lines.append(f"- **Requires:** {names(skill.requires, anchor=True)}. **Required by:** {names(skill.required_by, anchor=True)}.")
        lines.append(f"- **Install closure ({len(skill.closure)}):** {names(skill.closure)}.")
        lines.append(f"- **Optional routes in its instructions:** {names(skill.routes, anchor=True)}.")
        lines.append(f"- **Roles:** {roles}." + (f" **Search aliases:** {names(skill.aliases)}." if skill.aliases else ""))
        lines.append(f"- **Provenance:** {provenance(skill)}")
        lines.append(f"- **Folder:** [`skills/{skill.name}/`](../skills/{skill.name}/)")
        for title, section in (("Try this job", "Activation"), ("Keep these neighboring requests separate", "Near miss"), ("Check the result", "Outcome")):
            lines += ["", "#### " + title, "", *("> - " + example for example in skill.examples[section])]
        evidence = (f"[public evaluation summaries](../skills/{skill.name}/evals/results/)" if any((repo.root / "skills" / skill.name / "evals/results").glob("*.md")) else "no public evaluation summaries recorded")
        lines += ["", f"[Complete method](../skills/{skill.name}/SKILL.md), [all source examples](../skills/{skill.name}/evals/examples.md); {evidence}."]
    return "\n".join(lines)


def upstream(skill: Skill):
    for prefix, label, home in UPSTREAMS:
        if skill.source and skill.source.startswith(prefix):
            return label, home
    if skill.source:
        parts = skill.source.split("/")
        return "/".join(parts[3:5]), "/".join(parts[:5])
    return None, None


def provenance(skill: Skill) -> str:
    label, _ = upstream(skill)
    legal = f" Legal files: {', '.join(f'`{name}`' for name in skill.legal)}." if skill.legal else ""
    if not label:
        return "original to this repository." + legal
    revision = f" at `{str(skill.revision)[:7]}`" if skill.revision else ""
    return f"adapted from [{label}]({skill.source}){revision}." + legal


def render_typed(repo: Repo) -> str:
    lines = ["| Command | Claude Code | Codex | Requires | What it does |", "| --- | --- | --- | --- | --- |"]
    for skill in repo.skills.values():
        if skill.typed:
            lines.append(f"| [`{skill.name}`](#{skill.name}) | `/{skill.name}` | `${skill.name}` | {names(skill.requires)} | {cell(skill.summary)} |")
    return "\n".join(lines)


def render_roles(repo: Repo) -> str:
    every = [skill.name for skill in repo.skills.values() if "all" in skill.roles]
    lines = [f"The catalog assigns {len(every)} common capabilities to every role: {names(every)}. These are coverage assignments; installation follows required edges only.", "",
             "| Role | Router | Capabilities the catalog assigns to this role |", "| --- | --- | --- |"]
    for role in repo.roles:
        router = repo.skills.get(role)
        status = (f"[`{role}`](../skills/{role}/), installs {len(router.closure)}" if router and router.kind == "role" else "planned")
        assigned = [skill.name for skill in repo.skills.values() if skill.kind == "capability" and role in skill.roles]
        lines.append(f"| `{role}` | {status} | {len(assigned)}: {names(assigned)} |")
    return "\n".join(lines)


def render_requires(repo: Repo) -> str:
    lines = ["| Skill | Requires | Required by | Installs |", "| --- | --- | --- | --- |"]
    for skill in sorted(repo.skills.values(), key=lambda skill: skill.name):
        if skill.requires or skill.required_by:
            lines.append(f"| [`{skill.name}`](skills.md#{skill.name}) | {names(skill.requires)} | {names(skill.required_by)} | {len(skill.closure)} |")
    alone = [skill.name for skill in sorted(repo.skills.values(), key=lambda skill: skill.name) if not skill.requires and not skill.required_by]
    return "\n".join(lines + ["", f"No requires edges in either direction ({len(alone)}): {names(alone)}."])


def render_routes(repo: Repo) -> str:
    lines = ["| Skill | Names these optional routes in its instructions |", "| --- | --- |"]
    for skill in sorted(repo.skills.values(), key=lambda skill: skill.name):
        if skill.routes:
            lines.append(f"| [`{skill.name}`](skills.md#{skill.name}) | {names(skill.routes)} |")
    return "\n".join(lines)


def render_profiles(repo: Repo) -> str:
    lines = []
    for skill in repo.skills.values():
        if skill.kind == "role":
            external = [name for name in skill.closure if name in repo.external]
            lines += [f"**`{skill.name}` installs {len(skill.closure)} skills:** {names(skill.closure)}."
                      + (f" External prerequisites: {names(external)}." if external else " No external prerequisites."), ""]
    return "\n".join(lines).rstrip() or "No role routers yet."


def render_upstream(repo: Repo) -> str:
    groups = {}
    for skill in repo.skills.values():
        label, home = upstream(skill)
        groups.setdefault((label, home), []).append(skill.name)
    lines = ["| Primary source | Skills |", "| --- | --- |"]
    for (label, home), members in sorted(groups.items(), key=lambda item: (item[0][0] is None, item[0][0] or "")):
        source = f"[{label}]({home})" if label else "Original to this repository"
        lines.append(f"| {source} | {len(members)}: {names(sorted(members))} |")
    files = Counter(name for skill in repo.skills.values() for name in skill.legal)
    lines += ["", "| Legal file | Skills that carry it |", "| --- | --- |"]
    lines += [f"| `{name}` | {count} |" for name, count in sorted(files.items())]
    return "\n".join(lines)


def render_records(repo: Repo) -> str:
    counts = Counter((host, model, validity) for validity, host, model in repo.records)
    rows = sorted({(host, model) for host, model, _ in counts})
    lines = ["| Host as recorded | Effective model | Valid | Invalid | Total |", "| --- | --- | ---: | ---: | ---: |"]
    for host, model in rows:
        valid, invalid = counts[(host, model, "valid")], counts[(host, model, "invalid")]
        other = sum(count for (h, m, v), count in counts.items() if (h, m) == (host, model) and v not in ("valid", "invalid"))
        lines.append(f"| `{host}` | `{model}` | {valid} | {invalid} | {valid + invalid + other} |")
    lines.append(f"| All | | {sum(1 for r in repo.records if r[0] == 'valid')} | {sum(1 for r in repo.records if r[0] == 'invalid')} | {len(repo.records)} |")
    return "\n".join(lines)


