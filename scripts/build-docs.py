def render_reference(repo: Repo, language: str = "en") -> str:
    ordered = sorted(repo.skills.values(), key=lambda skill: skill.name)
    lines = []
    for group_label, group in ((label('Typed only', language), [s for s in ordered if s.typed]), (label('Auto', language), [s for s in ordered if not s.typed])):
        lines.append(f"- **{group_label} ({len(group)}):** " + ", ".join(f"[`{s.name}`](#{s.name})" for s in group))
    for skill in ordered:
        lines += ["", f"### `{skill.name}`", "", skill.description, ""]
        how = (label('typed only: `/{name}` in Claude Code, `${name}` in Codex', language).format(name=skill.name) if skill.typed
               else label('model selection when the task fits', language))
        kind = "router" if skill.kind == "role" else "capability"
        lines.append(f"- **{label('Starts', language)}:** {how}. **{label('Kind', language)}:** {kind}. **{label('Status', language)}:** {skill.status}.")
        lines.append(f"- **{label('Requires', language)}:** {names(skill.requires, anchor=True, language=language)}. **{label('Required by', language)}:** {names(skill.required_by, anchor=True, language=language)}.")
        lines.append(f"- **{label('Install closure', language)} ({len(skill.closure)}):** {names(skill.closure, language=language)}.")
        lines.append(f"- **{label('Optional routes in its instructions', language)}:** {names(skill.routes, anchor=True, language=language)}.")
