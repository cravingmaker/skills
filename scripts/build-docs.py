def outside_blocks(text: str) -> str:
    """Hand-written text only: generated blocks and fenced code are blanked."""
    result, generated = [], False
    for line in skillprose.prose(text).split("\n"):
        if BEGIN.match(line):
            generated = True
        result.append("" if generated else line)
        if END.match(line):
            generated = False
    return "\n".join(result)


def heading_slugs(text: str) -> list[str]:
    found, counts = [], Counter()
    for line in skillprose.prose(text).split("\n"):
        heading = re.match(r"#{1,6}\s+(.*?)\s*#*\s*$", line)
        if heading:
            base = re.sub(r"[^\w\- ]", "", heading[1].strip().lower()).replace(" ", "-")
            found.append(base if not counts[base] else f"{base}-{counts[base]}")
            counts[base] += 1
    return found


def slugs(text: str) -> set[str]:
    return set(heading_slugs(text))


def strip_generated(text: str) -> str:
    """Hash authored bytes, including code; generated markers and bodies are omitted."""
    return re.sub(r"(?ms)^<!-- BEGIN GENERATED [^\n]+ -->\n.*?^<!-- END GENERATED [^\n]+ -->(?:\n|$)", "", text)


def structure(text: str) -> list[tuple]:
    """Ordered headings, table shapes, list items and verbatim fenced code blocks."""
    events, fence, code, table = [], None, [], []
    for line in text.splitlines() + [""]:
        # Block quotes may contain list items or fences (source example prompts).
        body = re.sub(r"^(?: {0,3}> ?)+", "", line)
        stripped = body.lstrip()
        if fence:
            if re.fullmatch(re.escape(fence[0]) + "{" + str(fence[1]) + r",}\s*", stripped):
                events.append(("code", fence[2], tuple(code)))
                fence, code = None, []
            else:
                code.append(body)
            continue
        if table and not stripped.startswith("|"):
            events.append(("table", tuple(table)))
            table = []
        if match := re.match(r"(`{3,}|~{3,})(.*)$", stripped):
            fence = (match[1][0], len(match[1]), match[2].strip())
        elif match := re.match(r"(#{1,6})\s+", body):
            events.append(("heading", len(match[1])))
        elif stripped.startswith("|"):
            table.append(len(re.split(r"(?<!\\)\|", stripped.strip("|"))))
        elif match := re.match(r"(\s*)([-+*]|\d+[.)])\s+", body):
            events.append(("list", len(match[1]), "ordered" if match[2][0].isdigit() else "bullet"))
    if fence:
        events.append(("unclosed-code",))
    return events


def handbook_pairs(docs: dict, problems: list) -> list[tuple[str, str]]:
    english = {path for path in docs if path.startswith("handbook/") and not is_indonesian(path)}
    translated = {"handbook/" + path.removeprefix("handbook/id/") for path in docs if is_indonesian(path)}
    pairs = []
    for en in sorted(english | translated):
        ind = "handbook/id/" + en.removeprefix("handbook/")
        if en not in english:
            problems.append(f"{en} and {ind}: missing English counterpart; mirror every page in both languages")
        elif en not in translated:
            problems.append(f"{en} and {ind}: missing Indonesian counterpart; mirror every page in both languages")
        else:
            pairs.append((en, ind))
    return pairs


def check_structure(root: Path, docs: dict, pairs: list, problems: list) -> None:
    anchors = {}
    for en, ind in pairs:
        if structure(docs[en]) != structure(docs[ind]):
            problems.append(f"{en} and {ind}: structure mismatch; keep headings, tables, code blocks and list items in the same order")
        anchors[ind] = dict(zip(heading_slugs(docs[ind]), heading_slugs(docs[en])))

    def canonical(path, target):
        target = unquote(html.unescape(target.strip("<>")))
        if re.match(r"[a-z][a-z0-9+.-]*:", target):
            return target
        file_part, _, anchor = target.partition("#")
        destination = ((root / path).parent / file_part if file_part else root / path).resolve()
        if not destination.is_relative_to(root):
            return target
        relative = destination.relative_to(root).as_posix()
        if is_indonesian(relative):
            anchor = anchors.get(relative, {}).get(anchor, anchor)
            relative = "handbook/" + relative.removeprefix("handbook/id/")
        return relative + ("#" + anchor if anchor else "")

    def targets(path):
        prose = skillprose.prose(docs[path])
        links = HTMLLinks()
        links.feed(prose)
        return [canonical(path, target) for target in skillprose.link_targets(prose) + links.targets]

    for en, ind in pairs:
        if targets(en) != targets(ind):
            problems.append(f"{en} and {ind}: structure mismatch in link targets; point to corresponding pages and headings in the same order")


def sync_manifest(docs: dict, pairs: list) -> dict:
    return {"version": 1, "pages": {en.removeprefix("handbook/"): {
            "english": hashlib.sha256(strip_generated(docs[en]).encode("utf-8")).hexdigest(),
            "indonesian": hashlib.sha256(strip_generated(docs[ind]).encode("utf-8")).hexdigest()}
            for en, ind in pairs}}


def check_sync(root: Path, manifest: dict, pairs: list, problems: list) -> None:
    path = root / "handbook/id/SYNC.json"
    try:
        recorded = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        recorded = {}
    if not isinstance(recorded, dict) or recorded.get("version") != 1 or not isinstance(recorded.get("pages"), dict):
        problems.append("handbook/id/SYNC.json: missing or invalid manifest; update both languages, then run scripts/build-docs.py --record-sync")
        recorded = {"pages": {}}
    for en, ind in pairs:
        name = en.removeprefix("handbook/")
        if recorded["pages"].get(name) != manifest["pages"][name]:
            problems.append(f"{en} and {ind}: authored text differs from handbook/id/SYNC.json; update both languages, then run scripts/build-docs.py --record-sync")
    if set(recorded["pages"]) - set(manifest["pages"]):
        problems.append("handbook/id/SYNC.json: removed page pairs remain; update both languages, then run scripts/build-docs.py --record-sync")


class HTMLLinks(HTMLParser):
    """Collect file links from prose HTML, including quoted and unquoted attributes."""

    def __init__(self):
        super().__init__()
        self.targets = []

    def handle_starttag(self, tag, attrs):
        self.targets.extend(value for key, value in attrs if key in ("href", "src") and value)


def check_docs(repo: Repo, docs: dict, problems: list) -> None:
    root, skills, headings = repo.root, repo.skills, {}
    for path, text in docs.items():
        prose = skillprose.prose(text)
        html_links = HTMLLinks()
        html_links.feed(prose)
        for target in skillprose.link_targets(prose) + html_links.targets:
            target = unquote(html.unescape(target.strip("<>")))
            if re.match(r"[a-z][a-z0-9+.-]*:", target):
                continue
            file_part, _, anchor = target.partition("#")
            destination = (root / path).parent / file_part if file_part else root / path
            known = destination.resolve().relative_to(root).as_posix() if destination.resolve().is_relative_to(root) else None
            if not destination.exists():
                problems.append(f"{path}: link {target} points to a missing file; fix the path")
            elif anchor and destination.suffix == ".md":
                if destination not in headings:
                    headings[destination] = slugs(docs.get(known) or destination.read_text(encoding="utf-8"))
                if anchor in headings[destination]:
                    continue
                problems.append(f"{path}: link {target} names a missing heading; fix the anchor")
        hand = outside_blocks(text)
        for match in skillprose.POINTER.finditer(hand):
            if any(token in match["name"] for token in ("<", ">", "{{", "}}")):
                continue  # A placeholder such as the `<name>` skill is an example, not a route.
            if match["name"] not in skills and match["name"] not in repo.external:
                problems.append(f"{path}: 'the `{match['name']}` skill' names no current skill; use its catalog name")
        if path == "handbook/choosing-skills.md":
            hand += "\n" + json.dumps(repo.guidance)
        for name in re.findall(r"`[/$]([a-z0-9]+(?:-[a-z0-9]+)*)`", hand):
            if name not in skills and name not in repo.reserved and name not in NOT_COMMANDS:
                problems.append(f"{path}: command `/{name}` names no current skill or reserved host command")
        header = HEADER_ID if is_indonesian(path) else HEADER
        contents = "## Daftar isi\n" if is_indonesian(path) else "## Contents\n"
        if path.startswith("handbook/") and text.split("\n", 1)[0] != header:
            problems.append(f"{path}: the first line must be exactly: {header}")
        if path.startswith("handbook/") and contents not in text:
            problems.append(f"{path}: add a {'Daftar isi' if is_indonesian(path) else 'Contents'} section so the page can be skimmed")
    for prefix in ("handbook/", "handbook/id/"):
        choosing = docs.get(prefix + "choosing-skills.md", "")
        for skill in skills.values():
            selected = ("/" if skill.typed else "") + skill.name
            if f"[`{selected}`](skills.md#{skill.name})" not in choosing:
                problems.append(f"{prefix}choosing-skills.md: no generated intent row for {skill.name}; regenerate and keep strict editorial coverage")
        typed_text = outside_blocks(docs.get(prefix + "typed-commands.md", ""))
        headed = set(re.findall(r"^#{2,4} .*?`/([a-z0-9-]+)`", typed_text, re.M))
        for skill in skills.values():
            if skill.typed and skill.name not in headed:
                problems.append(f"{prefix}typed-commands.md: add a section headed `/{skill.name}` for this typed-only skill")
            elif not skill.typed and skill.name in headed:
                problems.append(f"{prefix}typed-commands.md: `{skill.name}` is no longer typed-only; move or remove its section")
    for current, directories, files in os.walk(root):
        relative = Path(current).relative_to(root)
        parts = relative.parts
        directories[:] = sorted(d for d in directories if d not in SKIP_DIRS
                                and not (len(parts) == 4 and parts[0] == "skills" and parts[2:] == ("evals", "results")))
        for name in sorted(files):
            path = (relative / name).as_posix()
            if path in MENTION_ALLOWED or any(path.startswith(entry) for entry in MENTION_ALLOWED if entry.endswith("/")):
                continue
            try:
                data = (Path(current) / name).read_bytes()
                text = unquote(html.unescape(data.decode("utf-8")))
            except (UnicodeDecodeError, OSError):
                continue
            for number, line in enumerate(text.split("\n"), 1):
                if MENTION.search(line):
                    problems.append(f"{path}:{number}: agent-facing files must not point into handbook/; link human docs from README.md only")


def check_record_links(repo: Repo, problems: list) -> None:
    """Public result summaries must not link to absent private evidence."""
    for path in repo.result_paths:
        prose = skillprose.prose(path.read_text(encoding="utf-8"))
        links = HTMLLinks()
        links.feed(prose)
        for target in skillprose.link_targets(prose) + links.targets:
            target = unquote(html.unescape(target.strip("<>")))
            if re.match(r"[a-z][a-z0-9+.-]*:", target):
                continue
            file_part = target.partition("#")[0]
            destination = (path.parent / file_part).resolve() if file_part else path
            if not destination.is_relative_to(repo.root) or not destination.exists():
                problems.append(f"{path.relative_to(repo.root)}: record link {target} has no repository destination; use local-only code text for private evidence")


def run(root: Path, check: bool, record_sync: bool = False) -> int:
    repo = load(root)
    rendered = {"en": {block: function(repo) for block, (function, _) in BLOCKS.items()},
                "id": {block: function(repo, "id") for block, (function, homes) in BLOCKS.items()
                       if any(is_indonesian(home) for home in homes)}}
    # The Indonesian pages are one level deeper; generated skill links still
    # resolve to the same source files. Local skill anchors are unchanged.
    rendered["id"] = {block: text.replace("](../skills/", "](../../skills/") for block, text in rendered["id"].items()}
    problems, drift, written, docs, updates = [], [], [], {}, {}
    homes = {home for _, files in BLOCKS.values() for home in files}
    for path in sorted(set(human_docs(root)) | homes):
        file = root / path
        if not file.is_file():
            problems.append(f"{path}: missing; create it with its generated blocks")
            continue
        text = file.read_text(encoding="utf-8")
        updated = regenerate(path, text, rendered["id" if is_indonesian(path) else "en"], problems)
        if updated != text:
            if check or record_sync:
                drift.append(path)
                print(f"error: {path} has stale generated sections; run scripts/build-docs.py", file=sys.stderr)
            else:
                updates[path] = updated
        docs[path] = updated
    check_docs(repo, docs, problems)
    check_record_links(repo, problems)
    pairs = handbook_pairs(docs, problems)
    check_structure(root, docs, pairs, problems)
    manifest = sync_manifest(docs, pairs)
    if check:
        check_sync(root, manifest, pairs, problems)
    if not problems and not drift and record_sync:
        target = root / "handbook/id/SYNC.json"
        content = json.dumps(manifest, ensure_ascii=False, indent=2) + "\n"
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            target.write_text(content, encoding="utf-8")
            written.append("handbook/id/SYNC.json")
    elif not problems and not check and not record_sync:
        for path, updated in updates.items():
            (root / path).write_text(updated, encoding="utf-8")
            written.append(path)
    for problem in problems:
        print(f"error: {problem}", file=sys.stderr)
    print(json.dumps({"mode": "check" if check else "record-sync" if record_sync else "write", "files": sorted(docs), "stale": drift,
                      "written": written, "problems": len(problems)}, indent=2))
    return 1 if drift or problems else 0


def main(arguments: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    modes = parser.add_mutually_exclusive_group()
    modes.add_argument("--check", action="store_true", help="write nothing; exit 1 on stale sections, bilingual sync drift or rule failures")
    modes.add_argument("--record-sync", action="store_true", help="record authored hashes after updating both languages; refuse mismatched structure or invalid docs")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent, help="repository root (default: this checkout)")
    options = parser.parse_args(arguments)
    try:
        return run(options.root.resolve(), options.check, options.record_sync)
    except (SourceError, OSError, UnicodeDecodeError, json.JSONDecodeError, TypeError, AttributeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
