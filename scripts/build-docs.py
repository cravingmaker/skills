"""Generate the README skill index and the handbook's generated sections.

Usage: build-docs.py [--check] [--root DIR]
  (default)  Rewrite every generated section from catalog/skills.yaml,
             skills/*/SKILL.md and skills/*/evals/results/*.md.
  --check    Write nothing; exit 1 when a section is stale or a rule fails.

A generated section sits between these two lines; never edit inside them:
  <!-- BEGIN GENERATED <block>: ... -->
  <!-- END GENERATED <block> -->

Rules checked in both modes:
  - every block appears exactly once in each of its home files and matches its sources;
  - every handbook page starts with the human-documentation line (HEADER);
  - no agent-facing file mentions a path into handbook/ (see MENTION_ALLOWED);
  - intent-guide.json has a useful row for every catalog skill; the intent page is generated;
  - handbook/typed-commands.md has a heading with `/name` for exactly the typed-only skills;
  - in README.md, CHANGELOG.md and handbook/, relative links and #anchors resolve,
    "the `name` skill" pointers and `/name` or `$name` commands name real skills.

Python 3.12+ standard library only; reads a strict YAML subset and rejects anything else.
JSON summary on stdout; diagnostics on stderr. Exit: 0 current or rewritten, 1 stale
section, rule failure or unreadable source, 2 usage.
"""

