def evaluation_counts(records: list) -> Counter:
    counts = Counter()
    for record in records:
        if record["history"]:
            counts[record["history"]] += 1
            continue
        counts["valid"] += 1
        example = record["example"]
        if example.startswith("activation-"):
            key = record["observed"] if record["expected"] == "true" else "unknown"
            counts["activation-" + key] += 1
        elif example.startswith("near-miss-"):
            key = record["observed"] if record["expected"] == "false" else "unknown"
            counts["near-miss-" + key] += 1
        elif example.startswith("outcome-"):
            counts["outcome-" + record["value"]] += 1
        else:
            counts["other"] += 1
    return counts


