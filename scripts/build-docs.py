def regenerate(path: str, text: str, rendered: dict, problems: list) -> str:
    """Replace each generated block's body; malformed markers leave the file unchanged."""
    lines, output, index, seen = text.split("\n"), [], 0, Counter()
    while index < len(lines):
        begin = BEGIN.match(lines[index])
        if END.match(lines[index]):
            problems.append(f"{path}:{index + 1}: END GENERATED without a BEGIN line")
            return text
        if not begin:
            output.append(lines[index])
            index += 1
            continue
        block = begin[1]
        stop = next((j for j in range(index + 1, len(lines)) if BEGIN.match(lines[j]) or END.match(lines[j])), None)
        if stop is None or not END.match(lines[stop]) or END.match(lines[stop])[1] != block:
            problems.append(f"{path}:{index + 1}: generated block {block} needs its own END GENERATED {block} line")
            return text
        if block not in rendered:
            problems.append(f"{path}:{index + 1}: unknown generated block {block}; known: {', '.join(sorted(rendered))}")
            return text
        seen[block] += 1
        output += [f"<!-- BEGIN GENERATED {block}: {SOURCES_NOTE} -->", "", rendered[block], "", f"<!-- END GENERATED {block} -->"]
        index = stop + 1
    for block, (_, homes) in BLOCKS.items():
        if path in homes and seen[block] != 1:
            problems.append(f"{path}: needs exactly one generated block {block} (found {seen[block]}); add its BEGIN and END lines")
        elif path not in homes and seen[block]:
            problems.append(f"{path}: generated block {block} belongs only in {', '.join(homes)}")
    return "\n".join(output)


