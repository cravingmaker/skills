"""The complete, owned Codex policy format. No upstream YAML is imported."""

from pathlib import Path

HEADER = "# Generated by scripts/build-host-config.py from catalog/skills.yaml. Do not edit.\n"
USER_POLICY = HEADER + "policy:\n  allow_implicit_invocation: false\n"


def plan(repo) -> tuple[dict[Path, str | None], list[str]]:
    changes, problems = {}, []
    for name in repo.frontmatter:
        directory = repo.root / "skills" / name / "agents"
        path = directory / "openai.yaml"
        expected = USER_POLICY if repo.invocation(name) == "user" else None
        if directory.is_symlink() or path.is_symlink():
            problems.append(f"{path}: generated host configuration must not be a symlink")
            continue
        if directory.exists() and (not directory.is_dir() or any(p.name != "openai.yaml" for p in directory.iterdir())):
            problems.append(f"{directory}: only generated agents/openai.yaml is allowed")
            continue
        actual = path.read_text(encoding="utf-8") if path.is_file() else None
        if path.exists() and not path.is_file():
            problems.append(f"{path}: expected a regular generated file")
        elif actual is not None and not actual.startswith(HEADER):
            problems.append(f"{path}: foreign host file; reconcile it before generation")
        elif actual != expected:
            changes[path] = expected
    return changes, problems


def check(repo) -> list[str]:
    changes, problems = plan(repo)
    return problems + [f"{path}: host configuration drift; preview scripts/build-host-config.py, then run it with --apply" for path in changes]
